"use client";

import { useState, useMemo } from "react";
import {
    FileCode,
    Copy,
    Check,
    Download,
    RotateCcw,
    Plus,
    Trash2,
    Shield,
    Bot,
    Globe,
    Info
} from "lucide-react";
import { cn } from "@/lib/utils";

interface DisallowRule {
    id: string;
    path: string;
}

interface AllowRule {
    id: string;
    path: string;
}

const AI_BOTS = [
    { name: "GPTBot (OpenAI)", agent: "GPTBot" },
    { name: "ChatGPT-User", agent: "ChatGPT-User" },
    { name: "ClaudeBot (Anthropic)", agent: "ClaudeBot" },
    { name: "CCBot (Common Crawl)", agent: "CCBot" },
    { name: "PerplexityBot", agent: "PerplexityBot" },
];

export function RobotsTxtGeneratorTool() {
    const [defaultPolicy, setDefaultPolicy] = useState<"allow" | "disallow">("allow");
    const [sitemapUrl, setSitemapUrl] = useState("https://example.com/sitemap.xml");
    const [crawlDelay, setCrawlDelay] = useState<string>("");
    const [blockAiCrawlers, setBlockAiCrawlers] = useState(false);

    const [disallowRules, setDisallowRules] = useState<DisallowRule[]>([
        { id: "1", path: "/admin/" },
        { id: "2", path: "/api/" },
        { id: "3", path: "/private/" },
    ]);

    const [allowRules, setAllowRules] = useState<AllowRule[]>([
        { id: "1", path: "/public/" },
    ]);

    const [newDisallowPath, setNewDisallowPath] = useState("");
    const [newAllowPath, setNewAllowPath] = useState("");
    const [customAgent, setCustomAgent] = useState("*");
    const [copied, setCopied] = useState(false);

    // ─── Generate Real-time robots.txt ──────────────────────────────
    const generatedRobotsTxt = useMemo(() => {
        const lines: string[] = [];

        lines.push("# ========================================================");
        lines.push("# robots.txt generated by RapidKit (https://getrapidkit.me)");
        lines.push("# ========================================================");
        lines.push("");

        // Block AI crawlers section if checked
        if (blockAiCrawlers) {
            lines.push("# Disallow automated AI training scrapers");
            AI_BOTS.forEach((bot) => {
                lines.push(`User-agent: ${bot.agent}`);
                lines.push("Disallow: /");
                lines.push("");
            });
        }

        // Main agent policy
        lines.push(`User-agent: ${customAgent.trim() || "*"}`);

        if (defaultPolicy === "disallow" && disallowRules.length === 0) {
            lines.push("Disallow: /");
        } else {
            // Allow rules first
            allowRules.forEach((r) => {
                if (r.path.trim()) lines.push(`Allow: ${r.path.trim()}`);
            });

            // Disallow rules
            if (defaultPolicy === "disallow") {
                lines.push("Disallow: /");
            } else {
                disallowRules.forEach((r) => {
                    if (r.path.trim()) lines.push(`Disallow: ${r.path.trim()}`);
                });
                if (disallowRules.length === 0) {
                    lines.push("Disallow:");
                }
            }
        }

        // Crawl delay
        if (crawlDelay.trim() && !isNaN(Number(crawlDelay))) {
            lines.push(`Crawl-delay: ${crawlDelay.trim()}`);
        }

        // Sitemap
        if (sitemapUrl.trim()) {
            lines.push("");
            lines.push(`# XML Sitemap`);
            lines.push(`Sitemap: ${sitemapUrl.trim()}`);
        }

        return lines.join("\n");
    }, [defaultPolicy, sitemapUrl, crawlDelay, blockAiCrawlers, disallowRules, allowRules, customAgent]);

    const handleCopy = () => {
        navigator.clipboard.writeText(generatedRobotsTxt);
        setCopied(true);
        setTimeout(() => setCopied(false), 2000);
    };

    const handleDownload = () => {
        const blob = new Blob([generatedRobotsTxt], { type: "text/plain" });
        const url = URL.createObjectURL(blob);
        const a = document.createElement("a");
        a.href = url;
        a.download = "robots.txt";
        a.click();
        URL.revokeObjectURL(url);
    };

    const addDisallowRule = (e: React.FormEvent) => {
        e.preventDefault();
        if (!newDisallowPath.trim()) return;
        const formatted = newDisallowPath.startsWith("/") ? newDisallowPath.trim() : "/" + newDisallowPath.trim();
        setDisallowRules([...disallowRules, { id: Date.now().toString(), path: formatted }]);
        setNewDisallowPath("");
    };

    const addAllowRule = (e: React.FormEvent) => {
        e.preventDefault();
        if (!newAllowPath.trim()) return;
        const formatted = newAllowPath.startsWith("/") ? newAllowPath.trim() : "/" + newAllowPath.trim();
        setAllowRules([...allowRules, { id: Date.now().toString(), path: formatted }]);
        setNewAllowPath("");
    };

    const removeDisallowRule = (id: string) => {
        setDisallowRules(disallowRules.filter((r) => r.id !== id));
    };

    const removeAllowRule = (id: string) => {
        setAllowRules(allowRules.filter((r) => r.id !== id));
    };

    const handleReset = () => {
        setDefaultPolicy("allow");
        setCustomAgent("*");
        setCrawlDelay("");
        setBlockAiCrawlers(false);
        setSitemapUrl("https://example.com/sitemap.xml");
        setDisallowRules([
            { id: "1", path: "/admin/" },
            { id: "2", path: "/api/" },
        ]);
        setAllowRules([]);
    };

    return (
        <div className="grid grid-cols-1 lg:grid-cols-[1fr_420px] gap-8 items-start">
            {/* ─── Generator Settings & Rules ─── */}
            <div className="space-y-6">
                {/* 1. Default Access Policy */}
                <div className="p-6 sm:p-7 rounded-3xl bg-[rgb(12,12,18)] border border-[rgb(38,38,58)] shadow-xl space-y-5">
                    <div className="flex items-center justify-between">
                        <span className="text-xs font-bold uppercase tracking-wider text-cyan-400 flex items-center gap-2">
                            <Shield className="w-4 h-4" /> 1. Default Crawler Policy
                        </span>
                        <span className="text-[11px] font-mono text-[rgb(130,130,170)]">
                            User-agent: {customAgent}
                        </span>
                    </div>

                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                        <button
                            type="button"
                            onClick={() => setDefaultPolicy("allow")}
                            className={cn(
                                "p-4 rounded-2xl border text-left transition-all",
                                defaultPolicy === "allow"
                                    ? "bg-emerald-500/10 border-emerald-500/40 text-white shadow-lg"
                                    : "bg-[rgb(18,18,28)] border-[rgb(45,45,65)] text-[rgb(148,148,186)] hover:text-white"
                            )}
                        >
                            <div className="flex items-center justify-between mb-1">
                                <span className="text-xs font-bold text-emerald-400">Allow All Robots (Recommended)</span>
                                {defaultPolicy === "allow" && <Check className="w-4 h-4 text-emerald-400" />}
                            </div>
                            <p className="text-[11px] text-[rgb(120,120,160)] leading-relaxed">
                                Search engines can crawl all public pages, except paths you explicitly disallow below.
                            </p>
                        </button>

                        <button
                            type="button"
                            onClick={() => setDefaultPolicy("disallow")}
                            className={cn(
                                "p-4 rounded-2xl border text-left transition-all",
                                defaultPolicy === "disallow"
                                    ? "bg-rose-500/10 border-rose-500/40 text-white shadow-lg"
                                    : "bg-[rgb(18,18,28)] border-[rgb(45,45,65)] text-[rgb(148,148,186)] hover:text-white"
                            )}
                        >
                            <div className="flex items-center justify-between mb-1">
                                <span className="text-xs font-bold text-rose-400">Disallow All Robots</span>
                                {defaultPolicy === "disallow" && <Check className="w-4 h-4 text-rose-400" />}
                            </div>
                            <p className="text-[11px] text-[rgb(120,120,160)] leading-relaxed">
                                Blocks all search engines from indexing the site (for staging/private environments).
                            </p>
                        </button>
                    </div>

                    {/* AI Crawler blocker toggle */}
                    <div className="pt-2 border-t border-[rgb(35,35,50)]">
                        <label className="flex items-center justify-between p-3 rounded-2xl bg-[rgb(18,18,28)] border border-[rgb(45,45,65)] cursor-pointer hover:border-violet-500/40 transition-all">
                            <div className="flex items-center gap-3">
                                <Bot className="w-4 h-4 text-violet-400 shrink-0" />
                                <div>
                                    <span className="text-xs font-semibold text-white block">Block AI Training Bots</span>
                                    <span className="text-[11px] text-[rgb(110,110,150)]">
                                        Disallow GPTBot, ClaudeBot, CCBot &amp; PerplexityBot from scraping your content
                                    </span>
                                </div>
                            </div>
                            <input
                                type="checkbox"
                                checked={blockAiCrawlers}
                                onChange={(e) => setBlockAiCrawlers(e.target.checked)}
                                className="w-4 h-4 accent-violet-500 rounded"
                            />
                        </label>
                    </div>
                </div>

                {/* 2. Disallow / Allow Path Rules */}
                <div className="p-6 sm:p-7 rounded-3xl bg-[rgb(12,12,18)] border border-[rgb(38,38,58)] shadow-xl space-y-6">
                    <span className="text-xs font-bold uppercase tracking-wider text-cyan-400 flex items-center gap-2">
                        <FileCode className="w-4 h-4" /> 2. Disallow &amp; Allow Path Rules
                    </span>

                    {/* Disallow Rules input */}
                    <div className="space-y-3">
                        <label className="text-xs font-semibold text-white flex items-center justify-between">
                            <span>Disallow Paths (<code className="text-rose-400 font-mono text-[11px]">Disallow: /path/</code>)</span>
                            <span className="text-[10px] text-[rgb(120,120,160)]">Hidden from indexers</span>
                        </label>

                        <form onSubmit={addDisallowRule} className="flex gap-2">
                            <input
                                type="text"
                                value={newDisallowPath}
                                onChange={(e) => setNewDisallowPath(e.target.value)}
                                placeholder="e.g. /admin/, /checkout/, /temp/"
                                className="flex-grow px-4 py-2.5 rounded-xl bg-[rgb(18,18,28)] border border-[rgb(45,45,65)] text-sm text-white placeholder-[rgb(90,90,130)] focus:outline-none focus:border-rose-500/50 font-mono"
                            />
                            <button
                                type="submit"
                                className="px-4 py-2.5 rounded-xl bg-rose-500 hover:bg-rose-600 text-white text-xs font-bold transition-all flex items-center gap-1 shrink-0"
                            >
                                <Plus className="w-4 h-4" /> Add
                            </button>
                        </form>

                        <div className="flex flex-wrap gap-2 pt-1">
                            {disallowRules.map((rule) => (
                                <span
                                    key={rule.id}
                                    className="inline-flex items-center gap-1.5 px-3 py-1 rounded-lg bg-rose-500/10 border border-rose-500/30 text-xs font-mono text-rose-300"
                                >
                                    <span>{rule.path}</span>
                                    <button
                                        type="button"
                                        onClick={() => removeDisallowRule(rule.id)}
                                        className="hover:text-white transition-colors"
                                        title="Remove rule"
                                    >
                                        <Trash2 className="w-3 h-3" />
                                    </button>
                                </span>
                            ))}
                        </div>
                    </div>

                    {/* Allow Rules input */}
                    <div className="space-y-3 pt-3 border-t border-[rgb(35,35,50)]">
                        <label className="text-xs font-semibold text-white flex items-center justify-between">
                            <span>Allow Paths (<code className="text-emerald-400 font-mono text-[11px]">Allow: /path/</code>)</span>
                            <span className="text-[10px] text-[rgb(120,120,160)]">Exception inside disallowed folders</span>
                        </label>

                        <form onSubmit={addAllowRule} className="flex gap-2">
                            <input
                                type="text"
                                value={newAllowPath}
                                onChange={(e) => setNewAllowPath(e.target.value)}
                                placeholder="e.g. /public/, /api/webhook"
                                className="flex-grow px-4 py-2.5 rounded-xl bg-[rgb(18,18,28)] border border-[rgb(45,45,65)] text-sm text-white placeholder-[rgb(90,90,130)] focus:outline-none focus:border-emerald-500/50 font-mono"
                            />
                            <button
                                type="submit"
                                className="px-4 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-bold transition-all flex items-center gap-1 shrink-0"
                            >
                                <Plus className="w-4 h-4" /> Add
                            </button>
                        </form>

                        <div className="flex flex-wrap gap-2 pt-1">
                            {allowRules.map((rule) => (
                                <span
                                    key={rule.id}
                                    className="inline-flex items-center gap-1.5 px-3 py-1 rounded-lg bg-emerald-500/10 border border-emerald-500/30 text-xs font-mono text-emerald-300"
                                >
                                    <span>{rule.path}</span>
                                    <button
                                        type="button"
                                        onClick={() => removeAllowRule(rule.id)}
                                        className="hover:text-white transition-colors"
                                        title="Remove rule"
                                    >
                                        <Trash2 className="w-3 h-3" />
                                    </button>
                                </span>
                            ))}
                        </div>
                    </div>
                </div>

                {/* 3. Sitemap & Crawl Delay */}
                <div className="p-6 sm:p-7 rounded-3xl bg-[rgb(12,12,18)] border border-[rgb(38,38,58)] shadow-xl space-y-4">
                    <span className="text-xs font-bold uppercase tracking-wider text-cyan-400 flex items-center gap-2">
                        <Globe className="w-4 h-4" /> 3. Sitemap &amp; Server Load
                    </span>

                    <div className="grid grid-cols-1 sm:grid-cols-[1fr_140px] gap-3">
                        <div className="space-y-1">
                            <label className="text-xs font-semibold text-white">Sitemap URL</label>
                            <input
                                type="text"
                                value={sitemapUrl}
                                onChange={(e) => setSitemapUrl(e.target.value)}
                                placeholder="https://example.com/sitemap.xml"
                                className="w-full px-4 py-2.5 rounded-xl bg-[rgb(18,18,28)] border border-[rgb(45,45,65)] text-sm text-white placeholder-[rgb(90,90,130)] focus:outline-none focus:border-cyan-500/60 font-mono"
                            />
                        </div>

                        <div className="space-y-1">
                            <label className="text-xs font-semibold text-white">Crawl Delay (s)</label>
                            <input
                                type="number"
                                min="1"
                                max="60"
                                value={crawlDelay}
                                onChange={(e) => setCrawlDelay(e.target.value)}
                                placeholder="e.g. 10"
                                className="w-full px-4 py-2.5 rounded-xl bg-[rgb(18,18,28)] border border-[rgb(45,45,65)] text-sm text-white placeholder-[rgb(90,90,130)] focus:outline-none focus:border-cyan-500/60 font-mono text-center"
                            />
                        </div>
                    </div>
                </div>
            </div>

            {/* ─── Output Preview Pane ─── */}
            <div className="space-y-6">
                <div className="p-6 sm:p-7 rounded-3xl bg-[rgb(12,12,18)] border border-[rgb(38,38,58)] shadow-2xl space-y-4">
                    <div className="flex items-center justify-between">
                        <span className="text-xs font-bold uppercase tracking-wider text-cyan-400 flex items-center gap-1.5">
                            <FileCode className="w-4 h-4" /> robots.txt Output
                        </span>
                        <button
                            type="button"
                            onClick={handleReset}
                            className="text-xs text-[rgb(110,110,150)] hover:text-white transition-colors flex items-center gap-1"
                        >
                            <RotateCcw className="w-3 h-3" /> Reset
                        </button>
                    </div>

                    {/* Code block */}
                    <pre className="p-5 rounded-2xl bg-[rgb(8,8,14)] border border-[rgb(35,35,50)] font-mono text-xs text-emerald-300 leading-relaxed overflow-x-auto min-h-[320px] max-h-[460px] custom-scrollbar selection:bg-emerald-500/30 selection:text-white">
                        {generatedRobotsTxt}
                    </pre>

                    {/* Actions */}
                    <div className="flex gap-2">
                        <button
                            type="button"
                            onClick={handleCopy}
                            className="btn-primary flex-1 inline-flex items-center justify-center gap-2 py-3 text-xs font-bold"
                        >
                            {copied ? <Check className="w-4 h-4 text-emerald-300" /> : <Copy className="w-4 h-4" />}
                            <span>{copied ? "Copied robots.txt!" : "Copy to Clipboard"}</span>
                        </button>

                        <button
                            type="button"
                            onClick={handleDownload}
                            className="inline-flex items-center justify-center gap-1.5 px-4 py-3 rounded-xl bg-[rgb(20,20,32)] border border-[rgb(45,45,65)] text-xs font-bold text-white hover:border-cyan-500/50 hover:bg-[rgb(26,26,42)] transition-all"
                            title="Download robots.txt file"
                        >
                            <Download className="w-4 h-4 text-cyan-400" />
                            <span>Download</span>
                        </button>
                    </div>
                </div>

                {/* Information Card */}
                <div className="p-6 rounded-3xl bg-[rgb(12,12,18)] border border-[rgb(38,38,58)] space-y-3">
                    <h4 className="text-xs font-bold text-white uppercase tracking-wider flex items-center gap-2">
                        <Info className="w-4 h-4 text-cyan-400" /> Where do I place robots.txt?
                    </h4>
                    <p className="text-xs text-[rgb(130,130,170)] leading-relaxed">
                        Upload this file directly to the root directory of your website host (e.g. <code>public_html/robots.txt</code> or <code>public/robots.txt</code> in Next.js).
                    </p>
                    <p className="text-xs text-[rgb(130,130,170)] leading-relaxed">
                        It must be accessible at: <code className="text-cyan-300 font-mono">https://yourdomain.com/robots.txt</code>
                    </p>
                </div>
            </div>
        </div>
    );
}
